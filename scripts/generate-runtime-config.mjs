import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const envPath = path.join(projectRoot, '.env');
const outputPath = path.join(projectRoot, 'src', 'config', 'generatedRuntime.ts');

function parseEnv(source) {
  const values = {};
  for (const rawLine of source.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const separator = line.indexOf('=');
    if (separator < 1) continue;
    const key = line.slice(0, separator).trim();
    let value = line.slice(separator + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    values[key] = value;
  }
  return values;
}

const fileValues = existsSync(envPath) ? parseEnv(await readFile(envPath, 'utf8')) : {};
const value = (key, fallback = '') => (process.env[key] ?? fileValues[key] ?? fallback).trim();
const repositoryMode = value('LEXICON_REPOSITORY_MODE', 'mock') === 'http' ? 'http' : 'mock';
const apiBaseUrl = value('LEXICON_API_BASE_URL');
const buildEnvironment = value('LEXICON_BUILD_ENV', 'development') || 'development';

if (repositoryMode === 'http' && !apiBaseUrl) {
  throw new Error('LEXICON_API_BASE_URL is required when LEXICON_REPOSITORY_MODE=http.');
}
if (buildEnvironment === 'production' && apiBaseUrl && !apiBaseUrl.startsWith('https://')) {
  throw new Error('Production builds require an HTTPS LEXICON_API_BASE_URL.');
}

const config = {
  repositoryMode,
  apiBaseUrl,
  companyWebsite: value('LEXICON_COMPANY_WEBSITE'),
  playStoreUrl: value('LEXICON_PLAY_STORE_URL'),
  roadsideAssistancePhone: value('LEXICON_ROADSIDE_PHONE'),
  buildEnvironment
};

const output = `// Generated by scripts/generate-runtime-config.mjs. Keep this file committed for clean checkouts.\nexport const generatedRuntimeConfig = ${JSON.stringify(config, null, 2)} as const;\n`;
await writeFile(outputPath, output, 'utf8');
console.log(`Runtime configuration written for ${buildEnvironment} (${repositoryMode}).`);
